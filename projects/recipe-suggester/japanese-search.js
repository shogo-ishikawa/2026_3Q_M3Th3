/**
 * 表示名を変えずに、かな・漢字・よく使う料理名の別表記を照合します。
 * 未知の漢字を推測して読む機能ではありません。収録語を辞書へ追加して対応します。
 * 文字幅・英字大小・かなをそろえた上で、長い料理名から一度だけ置換します。
 */
const kanaCache = new Map();
function kana(value) {
  const original = String(value ?? '');
  if (kanaCache.has(original)) return kanaCache.get(original);
  const text = original.normalize('NFKC').toLowerCase()
    .replace(/[ァ-ヶ]/gu, character => String.fromCharCode(character.charCodeAt(0) - 0x60))
    .replace(/\s+/gu, ' ').trim();
  if (kanaCache.size >= 8192) kanaCache.clear();
  kanaCache.set(original, text);
  return text;
}

