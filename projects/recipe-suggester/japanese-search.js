const aliases = new Map();
for (const [common, ...alternatives] of groups) {
  for (const term of [common, ...alternatives]) {
    const key = kana(term), existing = aliases.get(key);
    if (existing !== undefined && existing !== common) throw new Error(`検索辞書の表記が重複しています：${term}`);
    aliases.set(key, common);
  }
}
const escape = value => value.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&');
const aliasPattern = new RegExp([...aliases.keys()].sort((a, b) => b.length - a.length).map(escape).join('|'), 'gu');
const cache = new Map();
const formCache = new Map();
const kanjiAliases = [...aliases].filter(([alias]) => /[\p{Script=Han}々]/u.test(alias));

/** 検索用の共通表記。表示名や保存データには書き戻しません。 */
export function normaliseJapaneseSearch(value) {
  const text = kana(value);
  if (cache.has(text)) return cache.get(text);
  const common = text.replace(aliasPattern, term => aliases.get(term));
  if (cache.size >= 4096) cache.clear();
  cache.set(text, common);
  return common;
}

// 高野豆腐→こうやどうふのような複合語でも、部分語の「豆腐」「とうふ」から
// 同じ候補へ届くようにします。追加の読みは別フィールドに保ち、隣の語を連結しません。
function searchForms(value) {
  const text = kana(value);
  if (formCache.has(text)) return formCache.get(text);
  const forms = new Set([text, normaliseJapaneseSearch(text)]);
  for (const [alias, common] of kanjiAliases) if (text.includes(alias)) forms.add(common);
  if (formCache.size >= 4096) formCache.clear();
  const result = [...forms];
  formCache.set(text, result);
  return result;
}

// 「ツナ」のかな部分一致を「こまつな」の末尾から作らないための区別です。
// 小松菜そのものを探す読みは残し、ツナを含む料理や材料だけを根拠にします。
function hasTunaReading(value) {
  return normaliseJapaneseSearch(value).replaceAll('こまつな', ' ').includes('つな');
}

/** 空白で分けた語をすべて含む料理を探します。語順は問いません。 */
export function matchesJapaneseQuery(fields, query) {
  const terms = kana(query).split(' ').filter(Boolean);
  if (!terms.length) return true;
  const values = (Array.isArray(fields) ? fields : [fields]).map(kana);
  const commonValues = values.flatMap(searchForms);
  const tunaPresent = values.some(hasTunaReading);
  return terms.every(term => (!hasTunaReading(term) || tunaPresent) &&
    (values.some(value => value.includes(term)) ||
    commonValues.some(value => value.includes(normaliseJapaneseSearch(term)))));
}


/** 名前にない語の数。同数なら、単語検索では括弧前の料理名が一致する単品を先にします。 */
export function japaneseQueryRank(primaryFields, query) {
  const terms = kana(query).split(' ').filter(Boolean);
  const missing = terms.reduce((missing,term) =>
    missing + Number(!matchesJapaneseQuery(primaryFields,term)),0);
  if (!missing && terms.length === 1 && primaryFields.some(field =>
    normaliseJapaneseSearch(field).split('(')[0].trim() === normaliseJapaneseSearch(terms[0]))) return -0.25;
  return missing;
}
