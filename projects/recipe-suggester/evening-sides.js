// 材料は2人分。栄養の計算と買い物には、材料台帳にある同じ分量を使う。
function side(id, name, category, method, minutes, portionLabel, ingredients, steps, reference, options = {}) {
  return {
    id: `evening-side-${id}`, name, role: 'side', family: 'small-dish',
    genre: options.genre ?? '和食', nature: 'home-cooked', servings: 2, minutes,
    displayCategory: category, displayMethod: method,
    portion: {amount: 1, unit: '皿', label: portionLabel}, staple: false, mealBase: false,
    mealSuitability: options.banshakuOnly ? [] : ['lunch', 'dinner'],
    tags: ['晩酌', ...(minutes <= 20 ? ['時短'] : []), ...(options.tags ?? [])],
    ingredients: ingredients.map(([id, amount]) => ({id, amount})), steps,
    ingredientsKnown: true, allergensKnown: true, shoppingKnown: true,
    sourceNote: `家庭用の配合から1人分の栄養を計算しています。料理と使い方の参考：${reference}`,
  };
}

